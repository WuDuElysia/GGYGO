"""Lifetime/grid particle UV animation, before source shader stream packing.

Only the serialized Whole Sheet/Lifetime mode is implemented. Unity frame
values are normalized cycles; the transported index is measured in frames.
The shader adapter wraps the next index before making UV2, independent of
texture sampler address mode. Niagara's native next UV does not wrap that row.
No UV animation clock is introduced: evaluation uses Particles.NormalizedAge.
"""
import math


class UVError(ValueError):
    pass


def validate_tiles(tiles, path):
    if len(tiles) != 2 or any(type(value) is not int or value <= 0 for value in tiles):
        raise UVError("%s UVModule requires positive integer tile counts" % path)


def contract(source, path):
    if source is None or not source["enabled"]:
        return {"tiles": (1, 1), "animated": False, "blend": False}
    for field, expected in (("mode", 0), ("timeMode", 0), ("animationType", 0)):
        if source[field] != expected:
            raise UVError("%s UVModule.%s=%r is not implemented" % (path, field, source[field]))
    tiles = (source["tilesX"], source["tilesY"])
    validate_tiles(tiles, path)
    cycles = source["cycles"]
    if isinstance(cycles, bool) or not isinstance(cycles, (float, int)) or not math.isfinite(cycles) or cycles < 0:
        raise UVError("%s UVModule.cycles requires a finite nonnegative value" % path)
    # A sprite's current and next-frame UVs are generated by its vertex factory.
    # Per-channel masks need a shader stream adapter; never ignore that mask.
    if source["uvChannelMask"] not in (-1, 255):
        raise UVError("%s UVModule per-channel mask=%r requires a stream adapter" % (path, source["uvChannelMask"]))
    if source["flipU"] != 0 or source["flipV"] != 0:
        raise UVError("%s UVModule flip probabilities require their birth-stable UV contract" % path)
    return {"tiles": tiles, "animated": True, "blend": True, "cycles": float(cycles)}


def entries(source, path, randoms, curve_program, minmax_curve_h, float_literal):
    """Return ordered spawn/update assignments and native SubUV properties."""
    plan = contract(source, path)
    if not plan["animated"]:
        return [], [("Particles.SubImageIndex", "Float", "0.0")], plan
    # Start Frame is sampled once per particle, independent of lifetime time.
    # Frame-over-time random is also a stable birth attribute, not a new rand()
    # every update; the source 0.9999 end value must not be rounded to 1.
    start = minmax_curve_h(source["startFrame"], "Emitter.NormalizedLoopAge", randoms.take(), curve_program[0])
    frame = minmax_curve_h(source["frameOverTime"], "Particles.NormalizedAge", randoms.take(), curve_program[1])
    count = plan["tiles"][0] * plan["tiles"][1]
    if source["startFrame"]["minMaxState"] == 0:
        spawn, start_value = [], start
    else:
        spawn, start_value = [("Particles.UStartFrame", "Float", start)], "Particles.UStartFrame"
    expression = "(frac(%s + (%s) * %s) * %s)" % (
        start_value,
        frame, float_literal(plan["cycles"]), float_literal(count))
    return spawn, [("Particles.SubImageIndex", "Float", expression)], plan


def stream_component(name, component, tiles):
    """Source UV/UV2/AnimBlend from unanimated quad UV and frame transport.

    MaterialRandomBinding transports the float index; source StableRandom is
    independently supplied through DP2. No dynamic-parameter slot is stolen.
    Unity's UV origin is bottom-left while frame ordering starts at top-left.
    """
    validate_tiles(tiles, "Sprite shader")
    x, y = tiles
    if name == "AnimBlend":
        return "frac(AtlasFrame)"
    frame = "floor(AtlasFrame)" if name == "UV" else "fmod(floor(AtlasFrame) + 1.0, %s)" % repr(float(x * y))
    if component == 0:
        return "((UV0.x + fmod(%s, %s)) / %s)" % (frame, repr(float(x)), repr(float(x)))
    return "(1.0 - (UV0.y + floor((%s) / %s)) / %s)" % (frame, repr(float(x)), repr(float(y)))
