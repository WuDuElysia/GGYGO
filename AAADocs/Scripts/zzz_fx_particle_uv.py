"""@file zzz_fx_particle_uv.py
@brief 粒子Grid/Lifetime纹理帧：整张或稳定随机单行，Sprite与Mesh共用原寿命求值。

运输索引以格为单位，材质在生成UV2前正确回绕；Mesh按真实UV通道mask应用。
随机行和随机曲线在原粒子出生时固定，不新增动画时钟。
"""
import math
import json


class UVError(ValueError):
    pass


def validate_tiles(tiles, path):
    if not isinstance(tiles, (list, tuple)) or len(tiles) != 2 or any(type(value) is not int or value <= 0 for value in tiles):
        raise UVError("%s UVModule requires positive integer tile counts" % path)


def contract(source, path, *, mesh=False):
    """返回可直接JSON往返的UV合同；格数保持两个严格正整数。"""
    if source is None or not source["enabled"]:
        return {"tiles": [1, 1], "animated": False, "blend": False}
    for field, expected in (("mode", 0), ("timeMode", 0)):
        if source[field] != expected:
            raise UVError("%s UVModule.%s=%r is not implemented" % (path, field, source[field]))
    tiles = [source["tilesX"], source["tilesY"]]
    validate_tiles(tiles, path)
    animation_type = source["animationType"]
    if animation_type not in (0, 1):
        raise UVError("%s UVModule.animationType=%r is not implemented" % (path, animation_type))
    if animation_type == 1 and (source["rowMode"] not in (0, 1)
            or source["rowMode"] == 0 and (type(source["rowIndex"]) is not int
                                         or not 0 <= source["rowIndex"] < tiles[1])):
        raise UVError("%s UVModule single-row selection requires a valid Custom/Random row" % path)
    cycles = source["cycles"]
    if isinstance(cycles, bool) or not isinstance(cycles, (float, int)) or not math.isfinite(cycles) or cycles < 0:
        raise UVError("%s UVModule.cycles requires a finite nonnegative value" % path)
    # A sprite's current and next-frame UVs are generated by its vertex factory.
    # Per-channel masks need a shader stream adapter; never ignore that mask.
    mask = source["uvChannelMask"]
    if type(mask) is not int or mask < -1 or mask > 255 or not mesh and mask not in (-1, 255):
        raise UVError("%s UVModule per-channel mask=%r requires a stream adapter" % (path, source["uvChannelMask"]))
    if source["flipU"] != 0 or source["flipV"] != 0:
        raise UVError("%s UVModule flip probabilities require their birth-stable UV contract" % path)
    result = {"tiles": tiles, "animated": True, "blend": True, "cycles": float(cycles)}
    if animation_type == 1:
        result.update(animation_type=1, row_mode=source["rowMode"], row_index=source["rowIndex"])
    if mesh:
        result["uv_channel_mask"] = mask
    return result


def entries(source, path, randoms, curve_program, minmax_curve_h, float_literal, *, mesh=False):
    """Return ordered spawn/update assignments and native SubUV properties."""
    plan = contract(source, path, mesh=mesh)
    if not plan["animated"]:
        return [], [("Particles.SubImageIndex", "Float", "0.0")], plan
    # Start Frame is sampled once per particle, independent of lifetime time.
    # Frame-over-time random is also a stable birth attribute, not a new rand()
    # every update; the source 0.9999 end value must not be rounded to 1.
    start = minmax_curve_h(source["startFrame"], "Emitter.NormalizedLoopAge", randoms.take(), curve_program[0])
    frame = minmax_curve_h(source["frameOverTime"], "Particles.NormalizedAge", randoms.take(), curve_program[1])
    count = plan["tiles"][0] if plan.get("animation_type") == 1 else plan["tiles"][0] * plan["tiles"][1]
    if source["startFrame"]["minMaxState"] == 0:
        spawn, start_value = [], start
    else:
        spawn, start_value = [("Particles.UStartFrame", "Float", start)], "Particles.UStartFrame"
    expression = "(frac(%s + (%s) * %s) * %s)" % (
        start_value,
        frame, float_literal(plan["cycles"]), float_literal(count))
    if plan.get("animation_type") == 1:
        if plan["row_mode"] == 1:
            row = "Particles.UEFX_AtlasRow"
            spawn.append((row, "Float", "min(floor(%s*%s),%s)" % (
                randoms.take(), float_literal(plan["tiles"][1]), float_literal(plan["tiles"][1]-1))))
        else:
            row = float_literal(plan["row_index"])
        expression = "(%s*%s+%s)" % (row, float_literal(plan["tiles"][0]), expression)
    return spawn, [("Particles.SubImageIndex", "Float", expression)], plan


def stream_component(name, component, tiles, *, animation_type=0):
    """Source UV/UV2/AnimBlend from unanimated quad UV and frame transport.

    MaterialRandomBinding transports the float index; source StableRandom is
    independently supplied through DP2. No dynamic-parameter slot is stolen.
    Unity's UV origin is bottom-left while frame ordering starts at top-left.
    """
    validate_tiles(tiles, "Sprite shader")
    x, y = tiles
    if name == "AnimBlend":
        return "frac(AtlasFrame)"
    if animation_type not in (0, 1):
        raise UVError("UV stream requires WholeSheet or SingleRow grid animation")
    if name == "UV":
        frame = "floor(AtlasFrame)"
    elif animation_type == 1:
        frame = "(floor(AtlasFrame/%s)*%s+fmod(floor(AtlasFrame)+1.0,%s))" % (repr(float(x)), repr(float(x)), repr(float(x)))
    else:
        frame = "fmod(floor(AtlasFrame) + 1.0, %s)" % repr(float(x * y))
    if component == 0:
        return "((UV0.x + fmod(%s, %s)) / %s)" % (frame, repr(float(x)), repr(float(x)))
    return "(1.0 - (UV0.y + floor((%s) / %s)) / %s)" % (frame, repr(float(x)), repr(float(y)))


def mesh_uv_adapter(source, path):
    """真实源mask只作用对应Mesh UV；输出UE UV约定，原FP再转回Unity一次。"""
    plan = contract(source, path, mesh=True)
    result = {"mode": "FXAnimatedMeshUV0" if plan["animated"] and plan["uv_channel_mask"] & 1 else "OriginalMeshUV0",
              "source_node": path, "source_module": source, "contract": plan}
    if result["mode"] == "FXAnimatedMeshUV0":
        u = stream_component("UV", 0, plan["tiles"], animation_type=plan.get("animation_type", 0))
        v = stream_component("UV", 1, plan["tiles"], animation_type=plan.get("animation_type", 0))
        result.update(inputs=["UV0", "AtlasFrame"], code="return float2(%s,1.0-(%s));" % (u, v),
                      frame_attribute="Particles.SubImageIndex", native_binding="MaterialRandomBinding")
    return result


def mesh_uv_material_contract(adapter):
    """先校验完整来源adapter，再返回实际材质执行合同；原始模块与节点仍保留在调用方证据。"""
    if adapter is None:
        return None
    if (not isinstance(adapter, dict) or not isinstance(adapter.get("source_node"), str)
            or not adapter["source_node"]):
        raise UVError("Mesh UV材质合同缺准确原节点来源")
    expected = mesh_uv_adapter(adapter.get("source_module"), adapter["source_node"])
    # 比较JSON运输形状，完整保留原模块和执行字段；不把布尔、整数或浮点互相当作同值。
    actual = json.loads(json.dumps(adapter, allow_nan=False))
    canonical = json.loads(json.dumps(expected, allow_nan=False))
    if json.dumps(actual, sort_keys=True, allow_nan=False) != json.dumps(canonical, sort_keys=True, allow_nan=False):
        raise UVError("Mesh UV材质合同与完整原模块／唯一算法不同")
    del actual["source_node"]
    del actual["source_module"]
    return actual
